"""Человекочитаемые названия прав для админки.

Формат description в БД:
  первая строка — заголовок;
  дальше — обычное описание;
  после строки «---» — необязательное пояснение (в UI — иконка).
"""

from __future__ import annotations

from app.permissions import ALL_PERMISSION_CODES


def permission_description(title: str, body: str, note: str | None = None) -> str:
    text = f"{title.strip()}\n{body.strip()}"
    if note and note.strip():
        text += f"\n---\n{note.strip()}"
    return text


