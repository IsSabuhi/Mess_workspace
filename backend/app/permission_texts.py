def packed_permission_descriptions() -> dict[str, str]:
    return {
        code: permission_description(title, body, note)
        for code, (title, body, note) in PERMISSION_TEXTS.items()
    }


_missing = set(ALL_PERMISSION_CODES) - set(PERMISSION_TEXTS)
_extra = set(PERMISSION_TEXTS) - set(ALL_PERMISSION_CODES)
if _missing or _extra:
    raise RuntimeError(f"permission texts mismatch: missing={sorted(_missing)} extra={sorted(_extra)}")
